// Benchmark: excel-rs against other spreadsheet libraries for Node.js.
// Writes docs/benchmarks.md and the table in the README between the markers.
// Usage: npm run build (in npm/), then here: npm install && npm run bench
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync } from 'node:fs';
import { tmpdir, cpus } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { LIBS } from './libs.mjs';
import { makeRows, toCsv } from './data.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const ROWS = Number(process.env.BENCH_ROWS ?? 100_000);
const RUNS = Number(process.env.BENCH_RUNS ?? 5);

// Neutral input: the xlsx is written by SheetJS, not by excel-rs.
const XLSX = createRequire(import.meta.url)('xlsx');
const dir = mkdtempSync(path.join(tmpdir(), 'excel-rs-bench-'));
const rows = makeRows(ROWS);
const wb = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(rows, { cellDates: true }), 'S');
const files = { readXlsx: path.join(dir, 'in.xlsx'), readCsv: path.join(dir, 'in.csv') };
writeFileSync(files.readXlsx, XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' }));
writeFileSync(files.readCsv, toCsv(rows));

const TASKS = { readXlsx: 'Read xlsx', readCsv: 'Read csv (;)', writeXlsx: 'Write xlsx' };
const results = {};
for (const task of Object.keys(TASKS)) {
  results[task] = {};
  for (const lib of Object.keys(LIBS)) {
    const out = execFileSync(process.execPath, [path.join(here, 'case.mjs'), lib, task, files[task] ?? '', String(ROWS), String(RUNS)], {
      encoding: 'utf8',
      maxBuffer: 1 << 20,
    });
    const r = JSON.parse(out.trim().split('\n').pop());
    if (!r.unsupported && r.rows !== undefined && r.rows < ROWS) throw new Error(`${lib} ${task}: only ${r.rows} rows`);
    results[task][lib] = r;
    console.log(task.padEnd(10), lib.padEnd(16), r.unsupported ? '–' : `${r.ms.toFixed(0)} ms, ${r.peakMb.toFixed(0)} MB`);
  }
}

const fmt = (r, base) => {
  if (r.unsupported) return '–';
  const factor = base && r !== base ? ` (${(r.ms / base.ms).toFixed(1)}×)` : '';
  return `${Math.round(r.ms).toLocaleString('en-US')} ms${factor}`;
};
const header = `| Library | ${Object.values(TASKS).join(' | ')} | Peak memory (xlsx read) |\n| --- | ${Object.keys(TASKS).map(() => '---:').join(' | ')} | ---: |`;
const lines = Object.entries(LIBS).map(([lib, { label }]) => {
  const cells = Object.keys(TASKS).map((t) => fmt(results[t][lib], results[t]['excel-rs']));
  const mem = results.readXlsx[lib];
  return `| ${lib === 'excel-rs' ? `**${label}**` : label} | ${cells.join(' | ')} | ${mem.unsupported ? '–' : `${Math.round(mem.peakMb)} MB`} |`;
});
const cpu = cpus()[0]?.model.trim() ?? 'unknown CPU';
const note = `${ROWS.toLocaleString('en-US')} rows × 10 columns (text with umlauts, numbers, booleans, dates). Median of ${RUNS} runs after a warm-up, each library in its own process; (n×) = slower than excel-rs by that factor. Node ${process.versions.node}, ${cpu}, ${new Date().toISOString().slice(0, 10)}.`;
const table = `${header}\n${lines.join('\n')}\n\n${note}`;

writeFileSync(
  path.join(root, 'docs/benchmarks.md'),
  `# Benchmarks\n\nGenerated by \`npm/bench/bench.mjs\`. Run it again with \`cd npm && npm run build && cd bench && npm install && npm run bench\`.\n\n${table}\n\nThe xlsx input is written by SheetJS, so no library reads its own output. Every library returns rows of values; excel-rs and SheetJS return dates as \`Date\`. exceljs and SheetJS also read formatting, which excel-rs skips on purpose. node-xlsx is not listed: it wraps SheetJS 0.20.3.\n`,
);
const readmePath = path.join(root, 'README.md');
const readme = readFileSync(readmePath, 'utf8');
const marked = /(<!-- bench:start -->\n)[\s\S]*?(<!-- bench:end -->)/;
if (!marked.test(readme)) throw new Error('README markers missing');
writeFileSync(readmePath, readme.replace(marked, `$1${table}\n$2`));
console.log('\nwrote docs/benchmarks.md and README.md');
